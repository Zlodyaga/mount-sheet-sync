"""Routes and spawn points of rares for the world map: Routes.lua.

    python3 tools/catalog/routes.py [--write]     # without --write: only compare Routes.lua with the data

tools/catalog/rares/routes.json (written by hand from maps and wiki pages; every entry names its source) plus the mount
IDs of the catalog (column «ID существ» > «ID в игре») become ns.RARE_ROUTES: map ID > list of
{ mount = ID, spawns = { x, y, ... }, lines = { { x, y, x, y, ... }, ... } }; coordinates are the game's (0-100).
A line starts at its spawn point. Routes.lua is generated - do not edit it.
"""
import io
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
CATALOG = os.path.join(ROOT, "program", "catalog.json")
DATA = os.path.join(HERE, "rares", "routes.json")
LUA = os.path.join(ROOT, "Routes.lua")


def mount_ids():
    cat = json.load(io.open(CATALOG, encoding="utf-8"))
    out = {}
    for sheet in cat["sheets"]:
        cols = sheet["columns"]
        if "ID существ" not in cols or "ID в игре" not in cols:
            continue
        c_npc, c_id = cols.index("ID существ"), cols.index("ID в игре")
        for row in sheet["rows"]:
            for npc in str(row[c_npc]).replace(" ", "").split(","):
                if npc.isdigit() and str(row[c_id]).isdigit():
                    out.setdefault(int(npc), int(row[c_id]))
    return out


def num(v):
    return ("%.1f" % v).rstrip("0").rstrip(".")


def flat(points):
    return "{ " + ", ".join(num(c) for p in points for c in p) + " }"


def build():
    ids = mount_ids()
    maps = {}
    for e in json.load(io.open(DATA, encoding="utf-8")):
        if e["npc"] not in ids:
            raise SystemExit("routes.json: creature %d is not in the catalog" % e["npc"])
        spawns = list(e.get("spawns", [])) + [r["spawn"] for r in e.get("routes", [])]
        lines = [r["line"] for r in e.get("routes", []) if len(r["line"]) > 1]
        for p in spawns + [p for line in lines for p in line]:
            if not (0 <= p[0] <= 100 and 0 <= p[1] <= 100):
                raise SystemExit("routes.json: point %r of %s is outside the map" % (p, e["name"]))
        maps.setdefault(e["map"], []).append((ids[e["npc"]], e["name"], spawns, lines))
    out = ["-- Mount Sheet Sync: spawn points and routes of rares for the world map (Map.lua), by map ID.",
           "-- Generated by tools/catalog/routes.py from tools/catalog/rares/routes.json - do not edit.",
           "local _, ns = ...", "", "ns.RARE_ROUTES = {"]
    for m in sorted(maps):
        out.append("  [%d] = {" % m)
        for mount, name, spawns, lines in sorted(maps[m], key=lambda x: x[0]):
            out.append("    { mount = %d, spawns = %s,   -- %s" % (mount, flat(spawns), name))
            out.append("      lines = {" + ("" if lines else " } },"))
            for line in lines:
                out.append("        %s," % flat(line))
            if lines:
                out.append("      } },")
        out.append("  },")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    text = build()
    if "--write" in sys.argv:
        io.open(LUA, "w", encoding="utf-8", newline="\n").write(text)
        print("Routes.lua written")
        return 0
    have = io.open(LUA, encoding="utf-8", newline="").read().replace("\r\n", "\n") if os.path.exists(LUA) else ""
    if have != text:
        print("Routes.lua differs from the data: run tools/catalog/routes.py --write")
        return 1
    print("Routes.lua matches the data")
    return 0


if __name__ == "__main__":
    sys.exit(main())
