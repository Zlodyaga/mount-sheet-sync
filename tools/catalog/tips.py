"""Farming tips of the catalog for the addon's window: Tips.lua.

    python3 tools/catalog/tips.py [--write]     # without --write: only compare Tips.lua with the catalog

The catalog's column «Совет по фарму» (Russian) and its translations from program/sheet-i18n.json (English for every
row, German / French / Spanish / Portuguese where there are any — the rare monsters) become ns.FARM_TIPS:
language → mount ID → text. The addon shows the tip in the row's tooltip in its own language, English otherwise.
Several rows of one mount: the first tip. Characters the game's fonts cannot draw are replaced.
Tips.lua is generated — do not edit it; after a change of the catalog or of the translations run this with --write.
"""
import io
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
CATALOG = os.path.join(ROOT, "program", "catalog.json")
I18N = os.path.join(ROOT, "program", "sheet-i18n.json")
LUA = os.path.join(ROOT, "Tips.lua")
COLUMN, ID_COLUMN = "Совет по фарму", "ID в игре"
LANGS = ["ru", "en", "de", "fr", "es", "pt"]
# the game's fonts (at least the Russian client) draw a box for these
REPLACE = {"→": ">", "←": "<", "↑": "^", "↓": "v", "·": "-", "–": "-", " ": " "}


def clean(text):
    for a, b in REPLACE.items():
        text = text.replace(a, b)
    return " ".join(text.split())


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def tips():
    cat = json.load(io.open(CATALOG, encoding="utf-8"))
    i18n = json.load(io.open(I18N, encoding="utf-8"))
    out = {lang: {} for lang in LANGS}
    for sheet in cat["sheets"]:
        cols = sheet["columns"]
        if COLUMN not in cols or ID_COLUMN not in cols:
            continue
        c_tip, c_id = cols.index(COLUMN), cols.index(ID_COLUMN)
        for row in sheet["rows"]:
            tip = row[c_tip] if c_tip < len(row) else ""
            try:
                mount = int(row[c_id])
            except (TypeError, ValueError, IndexError):
                continue
            if not isinstance(tip, str) or not tip.strip() or mount <= 0 or mount in out["ru"]:
                continue
            out["ru"][mount] = clean(tip)
            en = i18n.get("content", {}).get(tip)
            if en:
                out["en"][mount] = clean(en)
            for lang in LANGS[2:]:
                own = i18n.get("contentL10n", {}).get(lang, {}).get(tip)
                if own:
                    out[lang][mount] = clean(own)
    return out


def lua_text():
    data = tips()
    lines = ["-- Mount Sheet Sync: farming tips of the catalog, by language and mount ID, for the row tooltips.",
             "-- Generated by tools/catalog/tips.py from program/catalog.json and program/sheet-i18n.json — do not edit.",
             "local _, ns = ...", "", "ns.FARM_TIPS = {"]
    for lang in LANGS:
        lines.append("  %s = {" % lang)
        for mount in sorted(data[lang]):
            lines.append("    [%d] = %s," % (mount, lua_string(data[lang][mount])))
        lines.append("  },")
    lines += ["}", ""]
    return "\n".join(lines)


def main():
    text = lua_text()
    old = io.open(LUA, encoding="utf-8", newline="").read() if os.path.exists(LUA) else ""
    if "--write" in sys.argv:
        io.open(LUA, "w", encoding="utf-8", newline="").write(text)
        data = tips()
        print("written %s (%s)" % (LUA, ", ".join("%s %d" % (lang, len(data[lang])) for lang in LANGS)))
        return 0
    if old != text:
        print("Tips.lua differs from the catalog: run tools/catalog/tips.py --write")
        return 1
    print("Tips.lua is up to date")
    return 0


sys.exit(main())
